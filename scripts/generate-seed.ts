/**
 * Writes supabase/seed.sql from the menu and zones in packages/core,
 * so the database and the app never disagree.
 * Run: npm run db:seed
 */
import { writeFileSync } from "node:fs";
import { MENU, ZONES } from "../packages/core/src";

const q = (s: string) => `'${s.replace(/'/g, "''")}'`;

const dishes = MENU.map(
  (d) =>
    `  (${[
      q(d.id),
      q(d.section),
      q(d.region),
      q(d.origin),
      d.price,
      d.dailySpecial,
      d.spicy,
      `array[${d.tags.map(q).join(", ")}]::text[]`,
      q(d.name.en),
      q(d.name.ar),
      q(d.description.en),
      q(d.description.ar),
    ].join(", ")})`,
);

const zones = ZONES.map((z) => `  (${[q(z.id), q(z.name.en), q(z.name.ar), z.feeQar].join(", ")})`);

const sql = `-- GENERATED by scripts/generate-seed.ts from packages/core. Do not edit by hand.

insert into public.dishes (id, section, region, origin, price_qar, daily_special, spicy, tags,
  name_en, name_ar, description_en, description_ar) values
${dishes.join(",\n")}
on conflict (id) do update set
  section = excluded.section, region = excluded.region, origin = excluded.origin,
  price_qar = excluded.price_qar, daily_special = excluded.daily_special, spicy = excluded.spicy,
  tags = excluded.tags, name_en = excluded.name_en, name_ar = excluded.name_ar,
  description_en = excluded.description_en, description_ar = excluded.description_ar;

insert into public.zones (id, name_en, name_ar, fee_qar) values
${zones.join(",\n")}
on conflict (id) do update set
  name_en = excluded.name_en, name_ar = excluded.name_ar, fee_qar = excluded.fee_qar;
`;

writeFileSync(new URL("../supabase/seed.sql", import.meta.url), sql);
console.log(`supabase/seed.sql: ${MENU.length} dishes, ${ZONES.length} zones`);
